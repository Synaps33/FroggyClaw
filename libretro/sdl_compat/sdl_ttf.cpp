static char s_ttf_error[128] = {0};

const char* TTF_GetError(void)
{
    return s_ttf_error;
}

int TTF_Init(void)
{
    return 0;
}

void TTF_Quit(void)
{
}

TTF_Font* TTF_OpenFont(const char* file, int ptsize)
{
    TTF_Font* f;

    /* Any font file works: glyphs come from the built-in table. Refusing to
     * open would abort BaseGameApp::Initialize, so succeed regardless. */
    (void)file;
    f = (TTF_Font*)calloc(1, sizeof(TTF_Font));
    if (f == NULL) {
        strncpy(s_ttf_error, "TTF_OpenFont: out of memory", sizeof(s_ttf_error) - 1);
        return NULL;
    }
    f->height = (ptsize > 0 && ptsize <= 32) ? ptsize : LINE_H;
    return f;
}

void TTF_CloseFont(TTF_Font* font)
{
    free(font);
}

int TTF_FontHeight(const TTF_Font* font)
{
    return font ? font->height : 0;
}

int TTF_SizeText(TTF_Font* font, const char* text, int* w, int* h)
{
    size_t len;
    (void)font;

    if (text == NULL)
        len = 0;
    else
        len = strlen(text);

    if (w) *w = (int)len * ADVANCE;
    if (h) *h = LINE_H;
    return 0;
}

SDL_Surface* TTF_RenderText_Blended(TTF_Font* font, const char* text, SDL_Color fg)
{
    SDL_Surface* surf;
    size_t len, i;
    int w, h;

    (void)font;
    if (text == NULL)
        text = "";

    len = strlen(text);
    w = (len ? (int)len * ADVANCE : 1);
    h = LINE_H;

    surf = SDL_CreateRGBSurface(0, w, h, 32,
                                0x000000FFu, 0x0000FF00u, 0x00FF0000u, 0xFF000000u);
    if (surf == NULL)
        return NULL;

    for (i = 0; i < len; i++) {
        unsigned char ch = (unsigned char)text[i];
        int gx, gy;
        Uint32 packed;

        if (ch < 0x20 || ch > 0x7E)
            ch = '?';

        packed = SDL_MapRGBA(surf->format, fg.r, fg.g, fg.b, 255);

        for (gy = 0; gy < GLYPH_H; gy++) {
            Uint8 bits = s_font[ch - 0x20][gy];
            for (gx = 0; gx < GLYPH_W; gx++) {
                if (bits & (0x10 >> gx)) {
                    int px = (int)i * ADVANCE + gx;
                    int py = gy + 1;
                    Uint32* p = (Uint32*)((Uint8*)surf->pixels + (size_t)py * surf->pitch);
                    p[px] = packed;
                }
            }
        }
    }

    return surf;
}
